#!/usr/bin/env node
// Regenerates the GitHub Pages architecture site from the committed
// Archify JSON IR under docs/architecture/archify/. The JSON is the
// source of truth (see docs/architecture/README.md); this script is
// the only place that turns it into viewable HTML, so the workflow
// and a local dev run always produce the same output from the same
// source — no separate manual regeneration step to forget.
//
// Usage:
//   node scripts/build-architecture-pages.mjs <archify-bin-path> <output-dir>
//
// <archify-bin-path> is the path to a checked-out Archify's
// bin/archify.mjs (see .github/workflows/architecture-pages.yml for
// the pinned commit used in CI). Diagram type is read directly from
// each JSON file's own "diagram_type" field — no separate mapping
// table to keep in sync when a diagram is added or renamed.

import { execFileSync } from 'node:child_process'
import { readFileSync, readdirSync, writeFileSync, mkdirSync } from 'node:fs'
import { join, basename } from 'node:path'
import { fileURLToPath } from 'node:url'

const REPO_ROOT = fileURLToPath(new URL('..', import.meta.url))
const SOURCE_DIR = join(REPO_ROOT, 'docs', 'architecture', 'archify')

// Only these four Archify types accept --repo-root / carry source
// evidence today (docs/architecture/README.md, "Source evidence").
const EVIDENCE_CAPABLE_TYPES = new Set(['architecture'])

function main() {
  const [, , archifyBinArg, outDirArg] = process.argv
  if (!archifyBinArg || !outDirArg) {
    console.error('Usage: build-architecture-pages.mjs <archify-bin-path> <output-dir>')
    process.exit(1)
  }
  const archifyBin = archifyBinArg
  const outDir = join(REPO_ROOT, outDirArg)
  mkdirSync(outDir, { recursive: true })

  const sourceFiles = readdirSync(SOURCE_DIR).filter((f) => f.endsWith('.json')).sort()
  if (sourceFiles.length === 0) {
    console.error(`No JSON IR files found under ${SOURCE_DIR}`)
    process.exit(1)
  }

  const built = []
  for (const file of sourceFiles) {
    const srcPath = join(SOURCE_DIR, file)
    const name = basename(file, '.json')
    const outPath = join(outDir, `${name}.html`)
    const spec = JSON.parse(readFileSync(srcPath, 'utf8'))
    const diagramType = spec.diagram_type
    if (!diagramType) {
      throw new Error(`${file} has no diagram_type — cannot render`)
    }

    const args = ['deliver', diagramType, srcPath, outPath, '--quality', 'showcase', '--json']
    if (EVIDENCE_CAPABLE_TYPES.has(diagramType)) {
      args.push('--repo-root', REPO_ROOT)
    }

    console.log(`Rendering ${file} (${diagramType}) -> ${outPath}`)
    const result = execFileSync('node', [archifyBin, ...args], { encoding: 'utf8' })
    const receipt = JSON.parse(result)
    if (!receipt.ok) {
      throw new Error(`Archify delivery failed for ${file}: ${JSON.stringify(receipt)}`)
    }
    built.push({ name, title: spec.meta?.title ?? name, diagramType })
  }

  writeFileSync(join(outDir, 'index.html'), renderIndex(built))
  console.log(`Built ${built.length} diagram(s) + index into ${outDir}`)
}

function renderIndex(diagrams) {
  const rows = diagrams
    .map(
      (d) =>
        `      <li><a href="${d.name}.html">${escapeHtml(d.title)}</a> <span class="type">${d.diagramType}</span></li>`
    )
    .join('\n')
  return `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<title>Sails Protocol — Architecture Diagrams</title>
<meta name="viewport" content="width=device-width, initial-scale=1">
<style>
  body { font-family: system-ui, sans-serif; max-width: 720px; margin: 3rem auto; padding: 0 1.5rem; color: #1a1a1a; }
  h1 { font-size: 1.4rem; }
  p.note { color: #555; }
  ul { padding-left: 1.2rem; }
  li { margin: 0.6rem 0; }
  .type { color: #888; font-size: 0.85em; }
  code { background: #f2f2f2; padding: 0.1em 0.3em; border-radius: 3px; }
</style>
</head>
<body>
<h1>Sails Protocol — Architecture Diagrams</h1>
<p class="note">Generated by <a href="https://github.com/tt-a1i/archify">Archify</a> from the JSON IR
committed at <code>docs/architecture/archify/</code> — that JSON, not this page, is the reviewed
source. See <a href="https://github.com/alan-schramm/Sails-Protocol/blob/main/docs/architecture/README.md">docs/architecture/README.md</a>
for scope, evidence coverage, and known residuals.</p>
<ul>
${rows}
</ul>
</body>
</html>
`
}

function escapeHtml(s) {
  return s.replace(/[&<>"']/g, (c) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' }[c]))
}

main()
